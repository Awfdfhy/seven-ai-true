const assert=require('assert');
const {CanonJourneyEngine}=require('./src/ultimate/canon-journey.js');
const {WorldTitleForge,TitleRegistry}=require('./src/ultimate/world-title-forge.js');

const journey=new CanonJourneyEngine({universeId:'crystal-world',strict:true});
journey.setExpectedUnits(['ep1','ep2']);
journey.addUnit({id:'ep1',order:1,kind:'episode',sourceRefs:['primary:ep1']});
journey.addUnit({id:'ep2',order:2,kind:'episode',sourceRefs:['primary:ep2']});
journey.addEvent({id:'e1',unitId:'ep1',order:1,summary:'The story begins',participants:['hero'],locations:['home'],requiredOutcomes:['hero_meets_mentor'],sourceRefs:['primary:ep1:scene1'],insertionSlots:[{id:'slot1',roles:['outsider','witness'],locationId:'home',participants:['hero'],maxImpact:'supportive'}]});
journey.addEvent({id:'e2',unitId:'ep2',order:1,summary:'The next canonical turn',participants:['hero','mentor'],locations:['town'],causes:['e1'],requiredOutcomes:['mentor_trusts_hero'],sourceRefs:['primary:ep2:scene1'],insertionSlots:[{id:'slot2',roles:['helper','companion'],locationId:'town',participants:['mentor'],maxImpact:'supportive'}]});
assert.equal(journey.coverageAudit().pass,true);
assert.equal(journey.canonBackbone().length,2);
assert.equal(journey.canonBackbone()[0].authority,'verified_canon_event');
const weave=journey.weavePlayer({id:'player'},{roles:['outsider','helper'],knownCharacterIds:['mentor'],beats:2});
assert.equal(weave.beats.length,2);
assert.equal(weave.entry.phase,'arrival');
assert.ok(weave.beats.every(b=>b.canonImpact==='interstitial_only'));
assert.deepEqual(weave.beats[0].mustPreserve,['hero_meets_mentor']);
const branch=journey.mediateAction('e2',{affects:['mentor_trusts_hero'],effect:'negate'});
assert.equal(branch.mode,'branch_required');
assert.equal(branch.preserveOriginal,true);
const reject=journey.mediateAction('e1',{unsourcedCanonClaim:true});
assert.equal(reject.mode,'reject_as_canon');
assert.ok(journey.accuracyContract().guarantees.includes('PLAYER_DIVERGENCE_BRANCHES'));

const incomplete=new CanonJourneyEngine({universeId:'broken',strict:true});
incomplete.setExpectedUnits(['missing']);
assert.equal(incomplete.coverageAudit().pass,false);
assert.throws(()=>incomplete.assertReady(),/CANON_COVERAGE_INCOMPLETE/);

const registry=new TitleRegistry();
const forge=new WorldTitleForge({worldId:'valen',registry,kindAliases:{episode:'Chronicle',side_story:'Whisper',what_if:'Fracture'},lexicon:{motifs:['crown','shadow','bell'],places:['valen'],symbols:['sun']}});
const dna=forge.learn({titles:['The First Bell','A Quiet Crown','Under the Blue Sun','The Broken Promise','Shadow at Noon']});
assert.equal(dna.count,5);
assert.ok(dna.length.median>=2);
assert.equal(forge.hierarchyLabel({kind:'episode',sequence:7,title:'The Silent Bell'}).inWorldKind,'Chronicle');
const packet=forge.promptPacket({kind:'side_story',summary:'A small story about a lost royal messenger',motifs:['bell'],candidateCount:6});
assert.equal(packet.task,'generate_world_native_title_candidates');
assert.equal(packet.styleDNA.intent.alias,'Whisper');
const exact=forge.evaluate('The First Bell');
assert.equal(exact.pass,false);
assert.ok(exact.issues.includes('EXACT_CANON_COPY'));
const pick=forge.choose(['The First Bell','Bell Beyond the Gate','Crown of Quiet Rain'],{});
assert.ok(pick.winner);
const saved=forge.reserveBest(['Bell Beyond the Gate','Crown of Quiet Rain'],{kind:'side_story',scopeId:'arc1',sequence:1});
assert.equal(saved.title.kind,'side_story');
assert.equal(registry.list('valen').length,1);
assert.equal(forge.audit().pass,true);
assert.throws(()=>registry.reserve({worldId:'valen',kind:'episode',title:saved.title.title}),/TITLE_COLLISION/);
console.log('ultimate canon journey + title forge: 27 assertions PASS');
