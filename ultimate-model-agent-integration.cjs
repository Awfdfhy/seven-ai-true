const assert=require('assert');
const {SevenUltimateOS}=require('./src/ultimate/runtime.js');
const {attachModelAgentV2}=require('./src/ultimate/model-agent-extension.js');

(async()=>{
 const os=new SevenUltimateOS();
 os.models.registerProvider({id:'fastp',freeProof:'verified_free',latencyMs:30,capabilities:['chat']});
 os.models.registerProvider({id:'deepp',freeProof:'local',local:true,latencyMs:70,capabilities:['chat']});
 os.models.registerModel({id:'fast-model',providerId:'fastp',roles:['general','coding','research','rpg'],quality:.82,speed:.98,context:16000,costClass:'free'});
 os.models.registerModel({id:'deep-model',providerId:'deepp',roles:['reasoning','coding','research','rpg'],quality:.95,speed:.75,context:64000,costClass:'free'});
 os.providers.register({id:'fastp',async *streamChat(){yield 'fast ';yield 'answer';}},{freeProof:'verified_free'});
 os.providers.register({id:'deepp',async *streamChat(){yield 'deep ';yield 'answer';}},{freeProof:'local',local:true});
 const attached=attachModelAgentV2(os);
 assert.ok(attached.modelControl&&attached.modelExecutor&&attached.agentFabric);
 assert.equal(os.agentFabricV2.registry.agents.size,5);
 assert.ok(os.modelEvolution.promptPrograms);
 assert.ok(os.modelEvolution.capabilityProbes);
 assert.ok(os.modelEvolution.capabilityDrift);
 assert.ok(os.modelEvolution.escalation);
 const plan=os.planRequest({text:'inspect and fix the code',role:'coding',complexity:.82,uncertainty:.65,risk:.45,verifiability:.9,latencyPriority:.3,contextTokens:5000,maxOutputTokens:800});
 assert.ok(plan.control);
 assert.ok(plan.control.strategy.mode!=='direct');
 assert.ok(plan.model.selected.modelId);
 const publicPlan=os.controller.publicPlan(plan);
 assert.ok(publicPlan.strategy);
 assert.ok(Array.isArray(publicPlan.fallbacks));
 const chunks=[];
 const result=await os.chat({id:'v2chat',text:'hello',messages:[{role:'user',content:'hello'}],role:'coding',complexity:.2,uncertainty:.1,risk:.1,latencyPriority:.9,onChunk:x=>chunks.push(x)});
 assert.ok(['completed','failed'].includes(result.execution?.status||result.run?.status));
 if((result.execution?.status||result.run?.status)==='completed')assert.ok(chunks.join('').includes('answer'));
 assert.ok(os.modelEvolution.experiences);
 assert.ok(os.modelAgentUI);
 const escalation=os.modelEvolution.escalation.decide({fastExpectedQuality:.5,strongExpectedQuality:.9,complexity:.9,risk:.7,latencyPriority:.15});
 assert.notEqual(escalation.tier,'fast');
 console.log('ultimate model-agent integration: 17 assertions PASS');
})().catch(err=>{console.error(err);process.exit(1)});